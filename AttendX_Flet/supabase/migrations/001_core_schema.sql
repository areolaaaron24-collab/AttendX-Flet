-- AttendX schema for a shared Supabase PostgreSQL database.
-- Apply to a fresh project using the Supabase SQL Editor or `supabase db push`.
-- No legacy passwords, QR tokens, face images, or fingerprint templates are imported here.

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  account_id text not null,
  role text not null check (role in ('TEACHER', 'STUDENT')),
  first_name text not null,
  last_name text not null,
  middle_name text not null default '',
  suffix text not null default '',
  sex text not null check (sex in ('Male', 'Female')),
  recovery_email text,
  course text,
  year_level text,
  section text,
  department text,
  office text,
  student_status text not null default 'ACTIVE' check (student_status in ('ACTIVE', 'DROPPED')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_student_fields check (
    (role = 'TEACHER') or (nullif(btrim(course), '') is not null and nullif(btrim(year_level), '') is not null and nullif(btrim(section), '') is not null)
  )
);
create unique index if not exists profiles_account_id_unique_ci on public.profiles (lower(btrim(account_id)));
create index if not exists profiles_role_active_idx on public.profiles(role, is_active);

create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  subject_name text not null unique,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint subjects_name_nonempty check (length(btrim(subject_name)) between 1 and 120)
);

create table if not exists public.classes (
  id bigint generated by default as identity primary key,
  course text not null,
  year_level text not null,
  section text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint classes_unique_group unique (course, year_level, section),
  constraint classes_nonempty check (length(btrim(course)) > 0 and length(btrim(year_level)) > 0 and length(btrim(section)) > 0)
);

create table if not exists public.schedules (
  id bigint generated by default as identity primary key,
  teacher_id uuid not null references public.profiles(id) on delete restrict,
  class_id bigint not null references public.classes(id) on delete restrict,
  subject_id bigint not null references public.subjects(id) on delete restrict,
  day_of_week text not null check (day_of_week in ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday')),
  start_time time not null,
  end_time time not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint schedules_end_after_start check (end_time > start_time),
  constraint schedules_no_exact_duplicate unique (teacher_id, class_id, subject_id, day_of_week, start_time, end_time)
);
create index if not exists schedules_teacher_day_time_idx on public.schedules(teacher_id, day_of_week, start_time);
create index if not exists schedules_class_active_idx on public.schedules(class_id, is_active);

-- Mirrors the legacy student_classes(student_id, schedule_id) workflow: enrollment is subject/schedule-specific.
create table if not exists public.class_enrollments (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  schedule_id bigint not null references public.schedules(id) on delete cascade,
  enrolled_at timestamptz not null default now(),
  constraint class_enrollments_unique unique (student_id, schedule_id)
);
create index if not exists class_enrollments_student_idx on public.class_enrollments(student_id, enrolled_at desc);
create index if not exists class_enrollments_schedule_idx on public.class_enrollments(schedule_id, student_id);

create table if not exists public.attendance_sessions (
  id bigint generated by default as identity primary key,
  schedule_id bigint not null references public.schedules(id) on delete cascade,
  teacher_id uuid not null references public.profiles(id) on delete restrict,
  session_token_hash text not null unique,
  session_date date not null,
  started_at timestamptz not null default now(),
  ends_at timestamptz not null,
  status text not null default 'ACTIVE' check (status in ('ACTIVE', 'CLOSED', 'FINALIZED')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint attendance_sessions_end_after_start check (ends_at > started_at),
  constraint attendance_session_schedule_date_unique unique(schedule_id, session_date)
);
create index if not exists attendance_sessions_teacher_status_idx on public.attendance_sessions(teacher_id, status, session_date desc);

create table if not exists public.attendance_records (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete restrict,
  schedule_id bigint not null references public.schedules(id) on delete cascade,
  session_id bigint references public.attendance_sessions(id) on delete set null,
  attendance_date date not null,
  attendance_time time not null,
  observed_at timestamptz not null,
  status text not null check (status in ('PRESENT', 'LATE', 'LATE_ABSENT', 'ABSENT')),
  method text not null check (method in ('QR', 'FACE', 'FINGERPRINT', 'SYSTEM', 'MANUAL')),
  created_at timestamptz not null default now(),
  constraint attendance_once_per_schedule_day unique(student_id, schedule_id, attendance_date)
);
create index if not exists attendance_student_date_idx on public.attendance_records(student_id, attendance_date desc);
create index if not exists attendance_schedule_date_status_idx on public.attendance_records(schedule_id, attendance_date desc, status);

-- Only hashed tokens are stored centrally; raw values are returned once to the issuing client.
create table if not exists public.qr_tokens (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.profiles(id) on delete cascade,
  schedule_id bigint not null references public.schedules(id) on delete cascade,
  token_hash text not null unique,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  revoked_at timestamptz
);
create index if not exists qr_tokens_student_schedule_idx on public.qr_tokens(student_id, schedule_id, expires_at desc);

-- Store a face descriptor, not a raw image. Access is restricted to the student and their assigned teachers.
create table if not exists public.face_templates (
  student_id uuid primary key references public.profiles(id) on delete cascade,
  embedding jsonb not null,
  algorithm text not null default 'face_recognition-128d',
  consented_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint face_embedding_is_array check (jsonb_typeof(embedding) = 'array' and jsonb_array_length(embedding) = 128)
);

-- Template ID is a sensor-local integer, not a phone/laptop OS fingerprint value.
create table if not exists public.fingerprint_credentials (
  student_id uuid primary key references public.profiles(id) on delete cascade,
  sensor_template_id integer not null unique check (sensor_template_id >= 0),
  finger_name text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  actor_role text check (actor_role in ('TEACHER', 'STUDENT')),
  action text not null,
  entity_type text,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists audit_logs_actor_created_idx on public.audit_logs(actor_id, created_at desc);

create table if not exists public.login_history (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  role text not null check (role in ('TEACHER', 'STUDENT')),
  login_at timestamptz not null default now(),
  client_label text not null default 'AttendX Flet'
);
create index if not exists login_history_profile_idx on public.login_history(profile_id, login_at desc);

-- Updated-at helper.
create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = public as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at before update on public.profiles for each row execute function public.set_updated_at();
drop trigger if exists subjects_set_updated_at on public.subjects;
create trigger subjects_set_updated_at before update on public.subjects for each row execute function public.set_updated_at();
drop trigger if exists classes_set_updated_at on public.classes;
create trigger classes_set_updated_at before update on public.classes for each row execute function public.set_updated_at();
drop trigger if exists schedules_set_updated_at on public.schedules;
create trigger schedules_set_updated_at before update on public.schedules for each row execute function public.set_updated_at();
drop trigger if exists sessions_set_updated_at on public.attendance_sessions;
create trigger sessions_set_updated_at before update on public.attendance_sessions for each row execute function public.set_updated_at();
drop trigger if exists face_templates_set_updated_at on public.face_templates;
create trigger face_templates_set_updated_at before update on public.face_templates for each row execute function public.set_updated_at();
drop trigger if exists fingerprints_set_updated_at on public.fingerprint_credentials;
create trigger fingerprints_set_updated_at before update on public.fingerprint_credentials for each row execute function public.set_updated_at();
